import assert from 'node:assert/strict'
import test from 'node:test'
import { fixture, identities, intent, startRound } from './helpers.js'

test('join informa sala ausente, personagem ocupado e sala cheia como erros fatais', async (t) => {
  const f = await fixture(t)
  const missing = await f.client()
  missing.send({ t: 'join', code: 'ZZZZZ', me: identities.guest })
  const absent = await missing.wait((m) => m.t === 'error')
  assert.equal(absent.code, 'ROOM_NOT_FOUND')
  assert.equal(absent.fatal, true)

  const { state } = await f.create({ maxPlayers: 2 })
  const taken = await f.client()
  taken.send({ t: 'join', code: state.code, me: { ...identities.guest, memberId: 'felipe' } })
  const occupied = await taken.wait((m) => m.t === 'error')
  assert.equal(occupied.code, 'MEMBER_TAKEN')
  assert.equal(occupied.fatal, true)

  await f.join(state.code)
  const full = await f.client()
  full.send({ t: 'join', code: state.code, me: identities.third })
  const capacity = await full.wait((m) => m.t === 'error')
  assert.equal(capacity.code, 'ROOM_FULL')
  assert.equal(capacity.fatal, true)
})

test('reconectar exige token e substitui o socket antigo sem desconectar a vaga', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: old, welcome } = await f.join(state.code)
  for (const token of [undefined, 'token-incorreto']) {
    const intruder = await f.client()
    intruder.send({ t: 'join', code: state.code, me: { ...identities.guest, sessionToken: token } })
    const error = await intruder.wait((m) => m.t === 'error')
    assert.equal(error.code, 'MEMBER_TAKEN')
    assert.equal(error.fatal, true)
  }
  const hostMark = host.mark()
  const { client: replacement, welcome: renewed } = await f.join(state.code, {
    ...identities.guest, sessionToken: welcome.sessionToken,
  })
  assert.equal(renewed.sessionToken, welcome.sessionToken)
  await old.waitClosed()
  await host.event('playerReconnected', hostMark)
  await replacement.barrier()
  assert.equal(replacement.latestState().players.find((p) => p.id === 'guest')?.connected, true)
  assert.equal(replacement.latestState().players.filter((p) => p.id === 'guest').length, 1)
  intent(replacement, { type: 'updateSettings', playerId: 'host', settings: { rounds: 7 } })
  const rejected = await replacement.wait((m) => m.t === 'error')
  assert.equal(rejected.code, 'BAD_INTENT')
  assert.notEqual(replacement.latestState().settings.rounds, 7)
})

test('queda durante rodada mantém respostas e o token restaura a mesma vaga', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: guest, welcome } = await f.join(state.code)
  const answering = await startRound(f, host)
  intent(guest, { type: 'answer', roundId: answering.round!.id, categoryId: 'nome', value: `${answering.round!.letter}na` })
  await guest.barrier()
  const mark = host.mark()
  await guest.close()
  await host.state((s) => s.players.some((p) => p.id === 'guest' && !p.connected), mark)
  const { state: restored } = await f.join(state.code, { ...identities.guest, sessionToken: welcome.sessionToken })
  assert.equal(restored.players.length, 2)
  assert.equal(restored.players.find((p) => p.id === 'guest')?.connected, true)
  assert.equal(restored.round!.answers.guest!.nome, `${answering.round!.letter}na`)
})

test('token continua obrigatório depois que o jogador sai da lista do lobby', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: guest, welcome } = await f.join(state.code)
  const mark = host.mark()
  await guest.close()
  await host.state((s) => s.players.every((p) => p.id !== 'guest'), mark)
  const intruder = await f.client()
  intruder.send({ t: 'join', code: state.code, me: identities.guest })
  const denied = await intruder.wait((m) => m.t === 'error')
  assert.equal(denied.code, 'MEMBER_TAKEN')
  assert.equal(denied.fatal, true)
  const { state: restored } = await f.join(state.code, { ...identities.guest, sessionToken: welcome.sessionToken })
  assert.equal(restored.players.filter((p) => p.id === 'guest').length, 1)
})

test('reconexão durante tolerância do lobby cancela a saída pendente', async (t) => {
  const f = await fixture(t, { lobbyGraceMs: 100 })
  const { client: host, state } = await f.create()
  const { client: guest, welcome } = await f.join(state.code)
  await guest.close()
  const { client: replacement } = await f.join(state.code, { ...identities.guest, sessionToken: welcome.sessionToken })
  await startRound(f, host)
  await replacement.barrier()
  assert.equal(replacement.latestState().players.find((p) => p.id === 'guest')?.connected, true)
  assert.equal(replacement.latestState().players.length, 2)
})

test('saída explícita remove o host no lobby e transfere o controle', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: guest } = await f.join(state.code)
  const mark = guest.mark()
  intent(host, { type: 'leave' })
  const updated = await guest.state((s) => s.players.length === 1, mark)
  assert.equal(updated.players[0]?.id, 'guest')
  assert.equal(updated.players[0]?.isHost, true)
  await host.waitClosed()
  intent(guest, { type: 'updateSettings', settings: { rounds: 2 } })
  await guest.state((s) => s.settings.rounds === 2, mark)
})

test('queda do host fora do lobby transfere host sem apagar histórico do jogador', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: guest } = await f.join(state.code)
  await startRound(f, host)
  const mark = guest.mark()
  await host.close()
  const updated = await guest.state((s) => s.players.some((p) => p.id === 'host' && !p.connected), mark)
  assert.equal(updated.players.length, 2)
  assert.equal(updated.players.find((p) => p.id === 'guest')?.isHost, true)
  assert.equal(updated.players.find((p) => p.id === 'host')?.isHost, false)
})

test('kick avisa o jogador antes de fechar e o bloqueia mesmo com token correto', async (t) => {
  const f = await fixture(t)
  const { client: host, state } = await f.create()
  const { client: guest, welcome } = await f.join(state.code)
  const mark = guest.mark()
  intent(host, { type: 'kick', targetId: 'guest' })
  const kicked = await guest.event('kicked', mark)
  assert.equal(kicked.playerId, 'guest')
  await guest.waitClosed()
  const eventTypes = guest.messages.slice(mark).flatMap((m) => m.events?.map((e) => e.type) ?? [])
  assert.ok(eventTypes.indexOf('kicked') < eventTypes.indexOf('playerLeft'))
  const retry = await f.client()
  retry.send({ t: 'join', code: state.code, me: { ...identities.guest, sessionToken: welcome.sessionToken } })
  const error = await retry.wait((m) => m.t === 'error')
  assert.equal(error.code, 'BANNED')
  assert.equal(error.fatal, true)
  assert.deepEqual(host.latestState().banned, [])
})
